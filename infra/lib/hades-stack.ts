import * as fs from 'fs';
import * as path from 'path';
import {
  Annotations,
  CfnOutput,
  Duration,
  Fn,
  RemovalPolicy,
  Stack,
  StackProps,
} from 'aws-cdk-lib';
import * as dynamodb from 'aws-cdk-lib/aws-dynamodb';
import * as cognito from 'aws-cdk-lib/aws-cognito';
import * as lambda from 'aws-cdk-lib/aws-lambda';
import * as logs from 'aws-cdk-lib/aws-logs';
import { DynamoEventSource, SqsDlq } from 'aws-cdk-lib/aws-lambda-event-sources';
import * as iam from 'aws-cdk-lib/aws-iam';
import * as sqs from 'aws-cdk-lib/aws-sqs';
import * as s3vectors from 'aws-cdk-lib/aws-s3vectors';
import * as apigwv2 from 'aws-cdk-lib/aws-apigatewayv2';
import { HttpLambdaIntegration } from 'aws-cdk-lib/aws-apigatewayv2-integrations';
import * as s3 from 'aws-cdk-lib/aws-s3';
import * as s3deploy from 'aws-cdk-lib/aws-s3-deployment';
import * as cloudfront from 'aws-cdk-lib/aws-cloudfront';
import * as origins from 'aws-cdk-lib/aws-cloudfront-origins';
import { RustFunction } from 'cargo-lambda-cdk';
import { Construct } from 'constructs';

export class HadesStack extends Stack {
  constructor(scope: Construct, id: string, props?: StackProps) {
    super(scope, id, props);

    // ---- DynamoDB -------------------------------------------------------
    const table = new dynamodb.Table(this, 'JournalTable', {
      tableName: 'hades_journal',
      partitionKey: { name: 'pk', type: dynamodb.AttributeType.STRING },
      sortKey: { name: 'sk', type: dynamodb.AttributeType.STRING },
      billingMode: dynamodb.BillingMode.PAY_PER_REQUEST,
      pointInTimeRecoverySpecification: { pointInTimeRecoveryEnabled: true },
      removalPolicy: RemovalPolicy.RETAIN,
      // Phase 2: feeds the notes indexer. Adding a stream is an in-place update.
      stream: dynamodb.StreamViewType.NEW_AND_OLD_IMAGES,
    });

    // ---- Cognito --------------------------------------------------------
    const userPool = new cognito.UserPool(this, 'UserPool', {
      userPoolName: 'hades-users',
      signInAliases: { email: true },
      selfSignUpEnabled: false,
      autoVerify: { email: true },
      accountRecovery: cognito.AccountRecovery.EMAIL_ONLY,
      removalPolicy: RemovalPolicy.RETAIN,
    });

    const userPoolClient = userPool.addClient('WebClient', {
      userPoolClientName: 'hades-web',
      generateSecret: false,
      authFlows: { userSrp: true, userPassword: true },
    });

    // ---- Notes bucket -----------------------------------------------------
    // Note content lives at users/<sub>/notes/<path>. This bucket is the source
    // of truth for notes, so it is versioned and retained on stack deletion
    // (no autoDeleteObjects).
    const notesBucket = new s3.Bucket(this, 'NotesBucket', {
      versioned: true,
      blockPublicAccess: s3.BlockPublicAccess.BLOCK_ALL,
      encryption: s3.BucketEncryption.S3_MANAGED,
      enforceSSL: true,
      removalPolicy: RemovalPolicy.RETAIN,
      lifecycleRules: [
        {
          id: 'NotesVersionHygiene',
          enabled: true,
          noncurrentVersionExpiration: Duration.days(90),
          expiredObjectDeleteMarker: true,
          abortIncompleteMultipartUploadAfter: Duration.days(7),
        },
      ],
    });

    // ---- Notes search (phase 2): S3 Vectors ----------------------------
    // The vectors are derived data (rebuildable with a backfill), but both are
    // retained to avoid surprise deletes. The bucket name is generated by
    // CloudFormation; Ref/IndexArn only expose ARNs, so the name is parsed out of
    // arn:aws:s3vectors:<region>:<account>:bucket/<name>.
    const vectorBucket = new s3vectors.CfnVectorBucket(this, 'VectorBucket', {});
    vectorBucket.applyRemovalPolicy(RemovalPolicy.RETAIN);
    const vectorBucketName = Fn.select(1, Fn.split('/', vectorBucket.attrVectorBucketArn));

    const vectorIndexName = 'notes';
    const vectorIndex = new s3vectors.CfnIndex(this, 'NotesVectorIndex', {
      vectorBucketArn: vectorBucket.attrVectorBucketArn,
      indexName: vectorIndexName,
      dataType: 'float32',
      dimension: 1024,
      distanceMetric: 'cosine',
      metadataConfiguration: {
        nonFilterableMetadataKeys: ['heading', 'snippet', 'title', 'updatedAt'],
      },
    });
    vectorIndex.applyRemovalPolicy(RemovalPolicy.RETAIN);
    // arn:aws:s3vectors:<region>:<account>:bucket/<bucket>/index/notes
    const vectorIndexArn = vectorIndex.attrIndexArn;

    const embedModelId = 'amazon.titan-embed-text-v2:0';
    const embedModelArn = `arn:${this.partition}:bedrock:${this.region}::foundation-model/${embedModelId}`;

    // ---- Lambda (Rust / Axum) -------------------------------------------
    // Log groups are defined here (rather than auto-created by Lambda on first run) so they
    // carry the stack's cost-allocation tag and don't keep logs forever. CDK-generated names
    // avoid clashing with any /aws/lambda/<fn> group Lambda already created.
    const apiLogs = new logs.LogGroup(this, 'ApiFunctionLogs', {
      retention: logs.RetentionDays.ONE_MONTH,
      removalPolicy: RemovalPolicy.DESTROY,
    });
    const fn = new RustFunction(this, 'ApiFunction', {
      manifestPath: path.join(__dirname, '../../backend/Cargo.toml'),
      binaryName: 'backend',
      logGroup: apiLogs,
      architecture: lambda.Architecture.ARM_64,
      memorySize: 256,
      timeout: Duration.seconds(10),
      environment: {
        TABLE_NAME: table.tableName,
        NOTES_BUCKET: notesBucket.bucketName,
        COGNITO_USER_POOL_ID: userPool.userPoolId,
        COGNITO_CLIENT_ID: userPoolClient.userPoolClientId,
        VECTOR_BUCKET: vectorBucketName,
        VECTOR_INDEX: vectorIndexName,
        EMBED_MODEL_ID: embedModelId,
        // AWS_REGION is set automatically by the Lambda runtime.
      },
    });
    // Includes PutItem/UpdateItem/DeleteItem/ConditionCheckItem, which is what
    // TransactWriteItems (notes move) is authorized against.
    table.grantReadWriteData(fn);
    // Object actions scoped to users/*: s3:GetObject* (incl. GetObjectVersion),
    // s3:PutObject, s3:DeleteObject* (incl. DeleteObjectVersion), s3:Abort*;
    // bucket-level s3:List* / s3:GetBucket* on the bucket ARN. CopyObject needs
    // GetObject on the source + PutObject on the destination, both covered.
    notesBucket.grantReadWrite(fn, 'users/*');
    // Search: QueryVectors with returnMetadata also requires GetVectors.
    fn.addToRolePolicy(
      new iam.PolicyStatement({
        sid: 'SearchVectors',
        actions: ['s3vectors:QueryVectors', 's3vectors:GetVectors'],
        resources: [vectorIndexArn],
      }),
    );
    fn.addToRolePolicy(
      new iam.PolicyStatement({
        sid: 'EmbedQuery',
        actions: ['bedrock:InvokeModel'],
        resources: [embedModelArn],
      }),
    );

    // ---- Indexer Lambda (phase 2) ---------------------------------------
    // Consumes the table stream (NOTE# items only), embeds note chunks with
    // Bedrock and writes them to the vector index. Also handles a manual
    // {"backfill": true} invoke.
    const indexerDlq = new sqs.Queue(this, 'IndexerDlq', {
      retentionPeriod: Duration.days(14),
      enforceSSL: true,
    });

    const indexerLogs = new logs.LogGroup(this, 'IndexerFunctionLogs', {
      retention: logs.RetentionDays.ONE_MONTH,
      removalPolicy: RemovalPolicy.DESTROY,
    });
    const indexer = new RustFunction(this, 'IndexerFunction', {
      manifestPath: path.join(__dirname, '../../backend/Cargo.toml'),
      binaryName: 'indexer',
      logGroup: indexerLogs,
      architecture: lambda.Architecture.ARM_64,
      memorySize: 512,
      // Generous for the one-off {"backfill": true} invoke, which reindexes sequentially;
      // it is safe to re-run (already-indexed notes are skipped) if it ever times out.
      timeout: Duration.minutes(5),
      environment: {
        TABLE_NAME: table.tableName,
        NOTES_BUCKET: notesBucket.bucketName,
        VECTOR_BUCKET: vectorBucketName,
        VECTOR_INDEX: vectorIndexName,
        EMBED_MODEL_ID: embedModelId,
      },
    });

    indexer.addEventSource(
      new DynamoEventSource(table, {
        startingPosition: lambda.StartingPosition.LATEST,
        batchSize: 10,
        maxBatchingWindow: Duration.seconds(5),
        bisectBatchOnError: true,
        retryAttempts: 3,
        reportBatchItemFailures: true,
        onFailure: new SqsDlq(indexerDlq),
        filters: [
          lambda.FilterCriteria.filter({
            dynamodb: { Keys: { pk: { S: lambda.FilterRule.beginsWith('NOTE#') } } },
          }),
        ],
      }),
    );

    // Stream read permissions are granted by the event source. Everything else
    // is explicit and least-privilege.
    indexer.addToRolePolicy(
      new iam.PolicyStatement({
        sid: 'ReadNoteContent',
        actions: ['s3:GetObject', 's3:GetObjectVersion'],
        resources: [notesBucket.arnForObjects('users/*')],
      }),
    );
    indexer.addToRolePolicy(
      new iam.PolicyStatement({
        sid: 'NoteMetadata',
        // UpdateItem: indexedHash/chunkCount write-back. Scan: backfill.
        actions: ['dynamodb:GetItem', 'dynamodb:Query', 'dynamodb:Scan', 'dynamodb:UpdateItem'],
        resources: [table.tableArn],
      }),
    );
    indexer.addToRolePolicy(
      new iam.PolicyStatement({
        sid: 'WriteVectors',
        actions: ['s3vectors:PutVectors', 's3vectors:DeleteVectors', 's3vectors:GetVectors'],
        resources: [vectorIndexArn],
      }),
    );
    indexer.addToRolePolicy(
      new iam.PolicyStatement({
        sid: 'EmbedChunks',
        actions: ['bedrock:InvokeModel'],
        resources: [embedModelArn],
      }),
    );

    // ---- HTTP API -------------------------------------------------------
    const httpApi = new apigwv2.HttpApi(this, 'HttpApi', {
      apiName: 'hades-api',
      // $default route -> Lambda. Auth is enforced in-app (Cognito JWT).
      defaultIntegration: new HttpLambdaIntegration('LambdaIntegration', fn),
    });

    // apiEndpoint looks like https://<id>.execute-api.<region>.amazonaws.com
    const apiDomain = Fn.select(2, Fn.split('/', httpApi.apiEndpoint));

    // ---- Frontend hosting ----------------------------------------------
    const siteBucket = new s3.Bucket(this, 'SiteBucket', {
      blockPublicAccess: s3.BlockPublicAccess.BLOCK_ALL,
      enforceSSL: true,
      encryption: s3.BucketEncryption.S3_MANAGED,
      removalPolicy: RemovalPolicy.DESTROY,
      autoDeleteObjects: true,
    });

    // SPA fallback: rewrite every non-file path to /index.html. Attached to
    // the S3 (default) behavior only so API 404s are not masked.
    const spaRewrite = new cloudfront.Function(this, 'SpaRewriteFunction', {
      runtime: cloudfront.FunctionRuntime.JS_2_0,
      code: cloudfront.FunctionCode.fromInline(`
function handler(event) {
  var request = event.request;
  var uri = request.uri;
  // Real files: Vite build output under /assets/, and top-level files such as
  // /config.json or /favicon.svg. Everything else is an SPA route, including
  // note URLs like /notes/Projects/Design.md that end in a file extension.
  var isAsset = uri.indexOf('/assets/') === 0;
  var isRootFile = uri.lastIndexOf('/') === 0 && uri.indexOf('.') !== -1;
  if (!isAsset && !isRootFile) {
    request.uri = '/index.html';
  }
  return request;
}
`),
    });

    const distribution = new cloudfront.Distribution(this, 'Distribution', {
      defaultRootObject: 'index.html',
      defaultBehavior: {
        origin: origins.S3BucketOrigin.withOriginAccessControl(siteBucket),
        viewerProtocolPolicy: cloudfront.ViewerProtocolPolicy.REDIRECT_TO_HTTPS,
        functionAssociations: [
          {
            function: spaRewrite,
            eventType: cloudfront.FunctionEventType.VIEWER_REQUEST,
          },
        ],
      },
      additionalBehaviors: {
        '/api/*': {
          origin: new origins.HttpOrigin(apiDomain, {
            protocolPolicy: cloudfront.OriginProtocolPolicy.HTTPS_ONLY,
          }),
          viewerProtocolPolicy: cloudfront.ViewerProtocolPolicy.REDIRECT_TO_HTTPS,
          cachePolicy: cloudfront.CachePolicy.CACHING_DISABLED,
          originRequestPolicy: cloudfront.OriginRequestPolicy.ALL_VIEWER_EXCEPT_HOST_HEADER,
          allowedMethods: cloudfront.AllowedMethods.ALLOW_ALL,
        },
      },
    });

    // ---- Frontend deployment --------------------------------------------
    const distDir = path.join(__dirname, '../../frontend/dist');
    if (fs.existsSync(distDir)) {
      new s3deploy.BucketDeployment(this, 'DeploySite', {
        destinationBucket: siteBucket,
        sources: [
          // A local-dev public/config.json would be copied into dist; never ship it.
          s3deploy.Source.asset(distDir, { exclude: ['config.json', 'config.example.json'] }),
          s3deploy.Source.jsonData('config.json', {
            apiUrl: '/api',
            region: this.region,
            userPoolId: userPool.userPoolId,
            userPoolClientId: userPoolClient.userPoolClientId,
          }),
        ],
        distribution,
        distributionPaths: ['/*'],
      });
    } else {
      Annotations.of(this).addWarning(
        `Frontend build not found at ${distDir}; skipping site deployment. ` +
          'Run `npm run build` in frontend/ and redeploy.',
      );
    }

    // ---- Outputs --------------------------------------------------------
    new CfnOutput(this, 'CloudFrontUrl', {
      value: `https://${distribution.distributionDomainName}`,
    });
    new CfnOutput(this, 'HttpApiUrl', { value: httpApi.apiEndpoint });
    new CfnOutput(this, 'TableName', { value: table.tableName });
    new CfnOutput(this, 'NotesBucketName', { value: notesBucket.bucketName });
    new CfnOutput(this, 'UserPoolId', { value: userPool.userPoolId });
    new CfnOutput(this, 'UserPoolClientId', { value: userPoolClient.userPoolClientId });
    new CfnOutput(this, 'Region', { value: this.region });
    new CfnOutput(this, 'VectorBucketName', { value: vectorBucketName });
    new CfnOutput(this, 'VectorIndexName', { value: vectorIndexName });
    new CfnOutput(this, 'IndexerDlqUrl', { value: indexerDlq.queueUrl });
    new CfnOutput(this, 'IndexerFunctionName', { value: indexer.functionName });
  }
}
